-- PostgreSQL
-- Initial schema and seed data for library system.

BEGIN;

DROP TABLE IF EXISTS book_categories CASCADE;
DROP TABLE IF EXISTS loans CASCADE;
DROP TABLE IF EXISTS books CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS categories CASCADE;


CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address TEXT NOT NULL,
    idcard_number VARCHAR(16) NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL, -- Not unique because multiple users may share the same phone number.
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    author VARCHAR(150) NOT NULL,
    publisher VARCHAR(150) NOT NULL,
    isbn VARCHAR(20) NOT NULL UNIQUE,
    published_year INTEGER NOT NULL,
    total_quantity INTEGER NOT NULL,
    available_quantity INTEGER NOT NULL,

    CONSTRAINT books_published_year_valid
        CHECK (published_year BETWEEN 1000 AND 9999),

    CONSTRAINT books_total_quantity_valid
        CHECK (total_quantity >= 0),

    CONSTRAINT books_available_quantity_valid
        CHECK (
            available_quantity >= 0
            AND available_quantity <= total_quantity
        )
);

-- A book can belong to multiple categories.
-- A category can contain multiple books.
CREATE TABLE book_categories (
    book_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    PRIMARY KEY (book_id, category_id),

    FOREIGN KEY (book_id)
        REFERENCES books (id) ON DELETE CASCADE,

    FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE CASCADE
);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    borrowed_at DATE NOT NULL,
    due_at DATE NOT NULL,
    returned_at DATE,

    FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,

    FOREIGN KEY (book_id)
        REFERENCES books (id) ON DELETE RESTRICT,

    CONSTRAINT loans_due_date_valid
        CHECK (due_at >= borrowed_at),

    CONSTRAINT loans_return_date_valid
        CHECK (
            returned_at IS NULL
            OR returned_at >= borrowed_at
        )
);


