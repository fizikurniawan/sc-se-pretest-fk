-- Q1. Books never borrowed
SELECT
    b.title AS "Buku"
FROM books b
WHERE NOT EXISTS (
    SELECT 1
    FROM loans l
    WHERE l.book_id = b.id
);

-- Q2. Get users with total fine
SELECT
    u.name AS "User",
    CONCAT(
        'Rp',
        SUM((l.returned_at - l.due_at) * 1000)
    ) AS "Denda"
FROM loans l
JOIN users u ON u.id = l.user_id
WHERE l.returned_at > l.due_at
GROUP BY u.id, u.name;

-- Q3. Get users with book loans
SELECT
    ROW_NUMBER() OVER (ORDER BY u.id) AS "No",
    u.name AS "User",
    STRING_AGG(b.title, ', ' ORDER BY b.id DESC) AS "Buku"
FROM users u
JOIN loans l ON l.user_id = u.id
JOIN books b ON b.id = l.book_id
GROUP BY u.id, u.name
ORDER BY u.id;
